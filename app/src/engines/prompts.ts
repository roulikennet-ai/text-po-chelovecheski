const LEVEL_RULES: Record<Intensity, string> = {
  1: 'Уровень 1 «Косметика»: только замена слов и удаление канцелярита внутри предложения. Не переноси части предложения, не меняй длину.',
  2: 'Уровень 2 «Лёгкая»: переформулируй предложение, разбей длинное на два. Не объединяй абзацы, не меняй последовательность тезисов.',
  3: 'Уровень 3 «Базовая»: переформулируй предложение целиком, меняй порядок членов, заменяй пассив на актив. Не меняй порядок предложений и абзацев.',
  4: 'Уровень 4 «Смелая»: переставляй предложения внутри абзаца, объединяй два коротких, добавляй связки. Не меняй порядок абзацев, не добавляй факты.',
  5: 'Уровень 5 «Свободный пересказ»: перерабатывай структуру абзаца целиком, пиши абзац заново в прозе. Не меняй порядок абзацев и разделов, не добавляй новые факты.',
};

const INVARIANTS = `ЖЁСТКИЕ ПРАВИЛА (нарушение недопустимо):
1. Токены вида ⟦Ч12⟧, ⟦И3⟧, ⟦Л1⟧ — это защищённые фрагменты. Верни каждый токен РОВНО один раз и дословно, на подходящем месте. Не меняй токены, не переводи их, не удаляй.
2. Не добавляй новую фактическую информацию. Ни одного нового факта, числа, имени, пояснения.
3. Не меняй направление и силу утверждений: «не повышает» остаётся отрицанием, «некоторые» не становится «все».
4. Не используй клише: «важно отметить», «следует подчеркнуть», «в современном мире», «играет важную роль», «комплексный подход» и подобные.
5. Не превращай прозу в список, если списка не было.
6. Не меняй порядок абзацев и разделов.
7. Пиши только итоговый текст абзаца, без комментариев и пояснений.`;

export function buildSystemPrompt(preset: PresetId, intensity: Intensity, compressTarget: CompressTarget): string {
  const parts = [
    'Ты — редактор научного русского текста. Твоя задача — переписать абзац так, чтобы он читался как текст, написанный человеком.',
    PRESET_RULES[preset],
    LEVEL_RULES[intensity],
  ];
  if (preset === 'F2') {
    parts.push(`Целевое сжатие: −${compressTarget}% объёма при сохранении всех фактов.`);
  }
  parts.push(INVARIANTS);
  return parts.join('\n\n');
}

export function buildUserPrompt(masked: string): string {
  return `Перепиши абзац по правилам. Верни только текст абзаца.\n\nАБЗАЦ:\n${masked}`;
}
