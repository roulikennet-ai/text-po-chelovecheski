/** Нормализация для поиска: нижний регистр, ё→е, схлопывание пробелов. */
export function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»""„"]/g, '"')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Предкомпилированный словарь в нормализованном виде. */
const NORMALIZED_CLICHES = CLICHES.map(normalize);

export interface ClicheHit {
  phrase: string;
  start: number;
  end: number;
}

/**
 * Найти вхождения клише в тексте. Возвращает позиции в исходной строке.
 * Длинные фразы проверяются первыми, чтобы «важно особо отметить» не
 * считалось как «важно отметить» дважды.
 */
export function findCliches(text: string): ClicheHit[] {
  const norm = normalize(text);
  const hits: ClicheHit[] = [];
  const order = NORMALIZED_CLICHES.map((p, i) => ({ p, i })).sort((a, b) => b.p.length - a.p.length);
  const consumed: Array<[number, number]> = [];

  for (const { p, i } of order) {
    let from = 0;
    for (;;) {
      const idx = norm.indexOf(p, from);
      if (idx === -1) break;
      const end = idx + p.length;
      // Не допускаем перекрытия уже найденных вхождений.
      const overlaps = consumed.some(([s, e]) => idx < e && end > s);
      if (!overlaps) {
        consumed.push([idx, end]);
        hits.push({ phrase: CLICHES[i], start: idx, end });
      }
      from = idx + 1;
    }
  }
  return hits.sort((a, b) => a.start - b.start);
}

/** Плотность клише на 1000 знаков (H2). */
export function clicheDensity(text: string): number {
  const chars = text.replace(/\s/g, '').length;
  if (chars === 0) return 0;
  return (findCliches(text).length / chars) * 1000;
}

