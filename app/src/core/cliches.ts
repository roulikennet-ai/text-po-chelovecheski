const COLLOQUIAL_SET = COLLOQUIAL_MARKERS.map(normalize);

/** Найти разговорные маркеры с позициями. */
export function findColloquial(text: string): Array<{ word: string; start: number; end: number }> {
  const norm = normalize(text);
  const res: Array<{ word: string; start: number; end: number }> = [];
  for (const w of COLLOQUIAL_SET) {
    let from = 0;
    for (;;) {
      const idx = norm.indexOf(w, from);
      if (idx === -1) break;
      const before = idx === 0 ? ' ' : norm[idx - 1];
      const after = idx + w.length >= norm.length ? ' ' : norm[idx + w.length];
      const boundaryBefore = !/[а-яa-z]/.test(before);
      const boundaryAfter = !/[а-яa-z]/.test(after);
      if (boundaryBefore && boundaryAfter) {
        res.push({ word: w, start: idx, end: idx + w.length });
      }
      from = idx + 1;
    }
  }
  return res.sort((a, b) => a.start - b.start);
}
