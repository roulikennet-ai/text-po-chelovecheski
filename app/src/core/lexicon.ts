/** Детерминированный выбор по строке (для стабильных вариантов). */
export function pick<T>(list: readonly T[], seed: string): T {
  let h = 0;
  for (let i = 0; i < seed.length; i++) {
    h = (h * 31 + seed.charCodeAt(i)) | 0;
  }
  const idx = Math.abs(h) % list.length;
  return list[idx];
}
